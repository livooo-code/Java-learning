package variable;

public class demo1{
	//main方法，表示程序主入口
	//类名需和文件名保持一致
	public static void main(String[] args){
		/*输出语句（打印语句）
		将括号里的内容进行打印输出*/
		//字符串、整数、小数、字符
		System.out.println("sakamoto days");
		System.out.println(666);
		System.out.println(-3.14);
		System.out.println('男');
		
		//布尔
		System.out.println(true);
		System.out.println(false);
		
		//空
		//null不能直接打印，只能通过字符串的方式打印
		System.out.println("null");
		
		//制表符
		System.out.println("Sakamoto"+'\t'+"nagumo");
	}
}